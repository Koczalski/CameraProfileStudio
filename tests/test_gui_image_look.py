    assert m.set_weight(0, 2.0) and edits
    assert m.data(m.index(0, m.COL_SHARE)) == "50%"
    assert m.set_included(2, False)
    assert [it.uid for it in m.included()] == [1, 2]
    assert m.data(m.index(0, m.COL_SHARE)) == "67%"
    assert m.data(m.index(2, m.COL_SHARE)) != "0%"  # excluded rows show no share
    assert m.data(m.index(2, m.COL_IMAGE), Qt.ItemDataRole.CheckStateRole) == Qt.CheckState.Unchecked
