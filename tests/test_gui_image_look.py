def idle(qtbot, w, timeout=120000):
    def done():
        if w.ctx.jobs.active():
            return False
        return not any(getattr(ws, "_debounce", None) is not None and ws._debounce.isActive() for ws in w.workspaces.values())

    qtbot.wait(50)
    qtbot.waitUntil(done, timeout=timeout)


def ws_of(win):
    return win.workspaces["imagelook"]


def analysed(qtbot, win, paths, target=None):
    ws = ws_of(win)
    ws.add_references([str(p) for p in paths])
    if target is not None:
        ws.preview.load(str(target))
    idle(qtbot, win)
    ws.analyze()
    idle(qtbot, win)
    return ws


