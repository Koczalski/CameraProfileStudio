def test_f6_removed_decode_drains_before_next_starts(qtbot, win, monkeypatch, gen):
    ws = ws_of(win)
    gate = threading.Event()
    running = []
    peak = []
    real = win.ctx.engine.load_image

    def blocked(*a, **k):
        running.append(1)
        peak.append(len(running))
        try:
            gate.wait(5)
            return real(*a, **k)
        finally:
            running.pop()

    monkeypatch.setattr(win.ctx.engine, "load_image", blocked)
    ws.add_references([str(gen["base"]), str(gen["cool"]), str(gen["chart"])])
    qtbot.waitUntil(lambda: len(running) == 1, timeout=5000)
    ws.remove_rows([0])  # remove the row being decoded
    qtbot.wait(200)
    assert len(running) == 1 and ws.model.items[0].state == "queued"  # next waits for the worker
    ws.cancel()  # cancel also drains rather than starting more work
    gate.set()
    idle(qtbot, win)
    assert max(peak) == 1
    assert [it.state for it in ws.model.items] == ["cancelled", "cancelled"]
    # loading resumes normally afterwards, still one at a time
    gate.set()
    ws.add_references([str(gen["warm"])])
    idle(qtbot, win)
    assert ws.model.items[-1].state == "ready" and max(peak) == 1


