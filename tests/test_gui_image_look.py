def test_single_reference_analysis_preview_export_readback(qtbot, win, tmp_path, gen):
    from camera_profile_studio import images, lut as lutmod
    from camera_profile_studio.types import SpaceSpec

    ws = analysed(qtbot, win, [gen["warm"]], target=gen["base"])
    assert ws.analysis is not None and len(ws.analysis.references) == 1
    assert ws.model.items[0].stats is not None and ws.model.items[0].stats.sha256
    assert "approximate_unverified" in ws.analysis.warnings
    assert "accuracy" in ws.diag_label.text()  # explicit "no score" statement
    assert "\u0394E" in ws.diag_label.text() and "mean" not in ws.diag_label.text().lower()
    assert ws.lut is not None and ws.export_button.isEnabled()
    assert ws.preview.viewer._after is not None and ws.preview.viewer.is_comparing()
    assert ws.preview.source.path.endswith("gen_base.png")  # target, not a reference
    ws.strength_spin.setValue(70)
    idle(qtbot, win)
    assert ws.lut.strength == pytest.approx(0.7)
    out = tmp_path / "look.cube"
    ws.export_to(str(out), False)
    idle(qtbot, win)
    assert out.exists() and out.with_suffix(".json").exists()
    back = lutmod.read_cube(out, input_space=SpaceSpec("srgb"), output_space=SpaceSpec("srgb"))
    np.testing.assert_allclose(back.values, ws.lut.raw.values, atol=1e-5)
    img = ws.preview.source.raw
    a = np.asarray(images.render_preview(img, ws.lut.raw).rgb)
    b = np.asarray(images.render_preview(img, back).rgb)
    np.testing.assert_allclose(a, b, atol=1e-4)
    meta = json.loads(out.with_suffix(".json").read_text(encoding="utf-8"))
    prov = meta["provenance"]
    assert prov["status"] == "approximate_unverified"
    refs = json.loads(prov["references"])
    assert refs[0]["sha256"] == ws.model.items[0].stats.sha256 and refs[0]["roi"] == [0.0, 0.0, 1.0, 1.0]
    settings = json.loads(prov["settings"])
    assert settings["tone_amount"] == 1.0 and settings["acknowledge_conflicts"] is False


