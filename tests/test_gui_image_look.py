def test_stale_analysis_completion_is_dropped(qtbot, win, monkeypatch, gen):
    ws = ws_of(win)
    ws.add_references([str(gen["base"])])
    idle(qtbot, win)
    gate = threading.Event()
    monkeypatch.setattr(win.ctx.engine, "analyze_image_look", lambda refs, s, token, progress=None: (gate.wait(5), _fake_view())[1])
    ws.analyze()
    qtbot.wait(50)
    ws.set_weight(0, 2.0)  # user edits while the analysis runs
    gate.set()
    win.ctx.jobs.pool.waitForDone(5000)
    qtbot.wait(100)
    assert ws.analysis is None and ws.lut is None and not ws.export_button.isEnabled()
    # completion already queued (worker finished) before the change
    monkeypatch.setattr(win.ctx.engine, "analyze_image_look", lambda refs, s, token, progress=None: _fake_view())
    ws.analyze()
    win.ctx.jobs.pool.waitForDone(5000)  # signal queued, not delivered
    ws.set_amount("tone_amount", 10)
    qtbot.wait(100)
    assert ws.analysis is None


def test_late_lut_from_old_analysis_is_dropped(qtbot, win, monkeypatch, gen):
    from camera_profile_studio.gui.backend import ImageLookBuild, LutData

    ws = ws_of(win)
    ws.add_references([str(gen["base"])])
    idle(qtbot, win)
    monkeypatch.setattr(win.ctx.engine, "analyze_image_look", lambda refs, s, token, progress=None: _fake_view())
    gate = threading.Event()

    def build(analysis, ack, size, strength, token, progress=None):
        gate.wait(5)
        lut = LutData(size=size, title="old", input_kind="srgb", output_kind="srgb", strength=strength, provenance=[])
        return ImageLookBuild(lut, [], ack, analysis)

    monkeypatch.setattr(win.ctx.engine, "build_image_look_lut", build)
    monkeypatch.setattr(win.ctx.engine, "render_preview", lambda *a, **k: (_ for _ in ()).throw(RuntimeError("no")))
    ws.analyze()
    qtbot.waitUntil(lambda: win.ctx.jobs.is_busy("imagelook:lut"), timeout=5000)
    ws.set_amount("color_amount", 10)  # invalidates analysis while the LUT build runs
    gate.set()
    win.ctx.jobs.pool.waitForDone(5000)
    qtbot.wait(100)
    assert ws.lut is None and not ws.export_button.isEnabled()


def test_cancel_analysis_and_reference_loads(qtbot, win, monkeypatch, gen):
    ws = ws_of(win)
    ws.add_references([str(gen["base"])])
    idle(qtbot, win)
    started = threading.Event()

    def slow(refs, s, token, progress=None):
        started.set()
        while not token.cancelled:
            threading.Event().wait(0.01)
        raise RuntimeError("should be reported as cancelled, not failed")

    monkeypatch.setattr(win.ctx.engine, "analyze_image_look", slow)
    ws.analyze()
    assert started.wait(5)
    assert ws.cancel_button.isEnabled()
    ws.cancel_button.click()
    idle(qtbot, win)
    assert ws.analysis is None and ws._analysis_error is None
    assert not ws.analyze_progress.isVisible() and ws.analyze_button.isEnabled()
    # queued reference decodes are cancelled one by one, never left "loading"
    gate = threading.Event()
    real = win.ctx.engine.load_image
    monkeypatch.setattr(win.ctx.engine, "load_image", lambda *a, **k: (gate.wait(5), real(*a, **k))[1])
    ws.add_references([str(gen["cool"]), str(gen["chart"])])
    qtbot.wait(50)
    assert sum(1 for r in win.ctx.jobs.active() if r.channel.startswith("imagelook:ref:")) == 1  # sequential
    ws.cancel()
