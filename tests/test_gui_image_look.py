def _scene(w: int = 360, h: int = 240, seed: int = 3) -> np.ndarray:
    """Procedural photo-like encoded-sRGB composition (sky, ground, objects)."""
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    y, x = yy / (h - 1), xx / (w - 1)
    img = np.empty((h, w, 3))
    sky = y < 0.55
    img[sky] = np.array([0.42, 0.58, 0.84]) * (0.7 + 0.3 * (1 - y[sky]))[:, None]
    img[~sky] = np.array([0.22, 0.28, 0.33]) * (0.55 + 0.45 * x[~sky])[:, None]
    for x0, y0, x1, y1, c in ((0.1, 0.5, 0.35, 0.62, (0.75, 0.18, 0.12)), (0.4, 0.45, 0.7, 0.6, (0.9, 0.88, 0.82)),
                              (0.55, 0.15, 0.57, 0.5, (0.12, 0.1, 0.08)), (0.75, 0.52, 0.92, 0.64, (0.2, 0.45, 0.25)),
                              (0.2, 0.3, 0.3, 0.45, (0.85, 0.7, 0.2))):
        img[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w)] = c
    img += rng.normal(0, 0.012, img.shape)
    return np.clip(img, 0, 1)


def _chart(w: int = 360, h: int = 240, seed: int = 7) -> np.ndarray:
    rng = np.random.default_rng(seed)
    img = np.zeros((h, w, 3))
    vals = rng.uniform(0.05, 0.95, (4, 6, 3))
    vals[0, 0], vals[3, 5] = 0.02, 0.98
    for r in range(4):
        for c in range(6):
            img[r * h // 4:(r + 1) * h // 4, c * w // 6:(c + 1) * w // 6] = vals[r, c]
    return img


@pytest.fixture(scope="session")
def gen(tmp_path_factory) -> dict[str, Path]:
    """Deterministic 8-bit PNG fixtures (generated, never downloaded)."""
    folder = tmp_path_factory.mktemp("image_look_fixtures")
    base = _scene()
    arrays = {"base": base, "warm": base * [1.06, 1.0, 0.94], "soft": 0.5 + (base - 0.5) * 0.75,
              "high": 0.5 + (base - 0.5) * 1.3, "cool": base * [0.94, 1.0, 1.06], "chart": _chart(),
              "black": np.zeros((64, 64, 3))}
    out = {}
    for name, arr in arrays.items():
        path = folder / f"gen_{name}.png"
        Image.fromarray((np.clip(arr, 0, 1) * 255 + 0.5).astype(np.uint8), "RGB").save(path)
        out[name] = path
    return out


