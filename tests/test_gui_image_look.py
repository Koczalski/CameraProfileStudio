def test_invalid_missing_and_unsupported_references(qtbot, win, tmp_path, gen):
    ws = ws_of(win)
    junk = tmp_path / "notes.txt"
    junk.write_text("x")
    raw = tmp_path / "frame.nef"
    raw.write_bytes(b"x")
    assert ws.add_references([str(junk), str(raw)]) == []  # RAW/other formats are not offered
    assert not ws.analyze_button.isEnabled() and "Add at least one" in ws.analyze_reason_label.text()
    # constant image: analysis error is shown, no LUT, nothing exportable
    ws.add_references([str(gen["black"])])
    idle(qtbot, win)
    ws.analyze()
    idle(qtbot, win)
    assert ws.analysis is None and ws.lut is None and not ws.export_button.isEnabled()
    assert ws._analysis_error is not None and ws._analysis_error.key == "error.code.image_look_unusable"
    assert "failed" in ws.diag_label.text().lower() and "failed" in ws.export_reason.text().lower()
    ws.remove_rows([0])
    # unreadable file: row fails, analysis disabled with the reason
    missing = tmp_path / "gone.png"
    ws.add_references([str(missing)])
    idle(qtbot, win)
    assert ws.model.items[0].state == "failed"
    assert not ws.analyze_button.isEnabled() and "gone.png" in ws.analyze_reason_label.text()
    ws.remove_rows([0])
    # file deleted after loading: engine I/O error surfaces
    copy = tmp_path / "copy.png"
    shutil.copy(gen["base"], copy)
    ws.add_references([str(copy)])
    idle(qtbot, win)
    copy.unlink()
    ws.analyze()
    idle(qtbot, win)
    assert ws.analysis is None and ws._analysis_error is not None
    assert ws._analysis_error.key in ("error.code.image_look_source_io", "error.file", "error.image")


def test_every_control_change_invalidates_result(qtbot, win, gen):
    ws = analysed(qtbot, win, [gen["warm"], gen["soft"]])
    assert ws.lut is not None

    def reanalyse():
        ws.analyze()
        idle(qtbot, win)
        assert ws.lut is not None and ws.export_button.isEnabled()

    changes = [
        lambda: ws.set_amount("tone_amount", 50),
        lambda: ws.set_amount("color_amount", 40),
        lambda: ws.set_amount("saturation_amount", 30),
        lambda: ws.set_weight(0, 1.5),
        lambda: ws.set_crop(0, (0.05, 0.05, 0.95, 0.95)),
        lambda: ws.set_included(1, False),
        lambda: ws.set_included(1, True),
        lambda: ws.seed.setValue(7),
        lambda: ws.analysis_size.setValue(64),
    ]
    for change in changes:
        change()
        assert ws.analysis is None and ws.lut is None and not ws.export_button.isEnabled()
        assert "Analyse again" in ws.export_reason.text()
        reanalyse()
    old = ws.analysis
    settings = json.loads(dict(ws.lut.provenance)["settings"])
    assert settings["tone_amount"] == 0.5 and settings["saturation_amount"] == 0.3 and settings["seed"] == 7
    # LUT-only settings rebuild from the same analysis; the old LUT is never exportable meanwhile
    ws.size_combo.setCurrentIndex(ws.size_combo.findData(17))
    assert ws.lut is None and not ws.export_button.isEnabled()
    idle(qtbot, win)
    assert ws.analysis is old and ws.lut is not None and ws.lut.size == 17


