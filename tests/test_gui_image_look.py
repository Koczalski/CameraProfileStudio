"""Image Look Creator GUI tests (offscreen Qt).

* Pure widget/model tests (ROI geometry, reference weights/inclusion) need no
  engine.
* Workflow tests drive the real ``camera_profile_studio.image_look`` engine
  on small *deterministic procedural* PNGs generated by this module into a
  temporary directory (no checked-in or downloaded images; a synthetic
  "scene" with warm/soft/high-contrast/cool pixel-math variants, a random
  patch chart and a constant black frame).  They exercise GUI plumbing only
  and are not evidence of look accuracy or cross-scene behaviour.  A missing
  engine module or image dependency is a test failure, never a skip.
* Race/cancellation tests replace the engine adapter calls with gated
  test-only stand-ins; nothing of that kind ships in the GUI.
"""

